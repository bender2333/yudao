// 决定卡片里按钮的点击区（工单 #1161）：画出来的按钮与"点这一块算点中"的范围是两回事。
//
// 卡片是像素画的，材料里的链接画出来只有 12 个逻辑像素高的一块小按钮，字只有 6.5 个像素；
// 试用时点在这一行文字上却没有反应，因为没点中那一小块，而纸面上的点击又被吞掉（`click` 在纸里
// 不做事也不返回 false）。这里把点击区放大到这一行文字：**只放宽点击区，画的像素一个都不变**，
// 所以回放的逐像素对照不受影响。
//
// 这块算数与画面无关，放在单独的文件里：楼层与页面的单元测试都能直接读它。

/** 画面逻辑坐标里的一块矩形。 */
export type CardRect = { x: number; y: number; w: number; h: number };

/**
 * 材料里链接的点击区放宽量：上下各 3 个逻辑像素，12 像素高的按钮因此占满这一行文字的 18 个像素；
 * 左右各 3 个，正好是两个链接之间留的 6 个像素的一半，相邻链接的点击区相接而不互相覆盖。
 */
export const LINK_HIT_PAD = 3;

/** 按钮的点击区：在画出来的按钮外面每边再放宽 pad 个逻辑像素（pad 为 0 就是按钮本身）。 */
export function hitRect(x: number, y: number, w: number, h: number, pad = 0): CardRect {
  return { x: x - pad, y: y - pad, w: w + pad * 2, h: h + pad * 2 };
}
